GENERATED_SDK_TEMPLATE = '\n'.join([
    "# LLM Cost Guard & Deterministic Router - Real Deliverable Artifact",
    "# Generated by PROVIPAGENT Autonomous Product Factory",
    "from dataclasses import dataclass",
    "from typing import Dict, List",
    "",
    "@dataclass",
    "class ModelRoute:",
    "    provider: str",
    "    model: str",
    "    cost_per_1k_tokens: float",
    "    max_latency_ms: int",
    "",
    "class CostGuardRouter:",
    "    def __init__(self, daily_budget_usd: float):",
    "        self.daily_budget_usd = daily_budget_usd",
    "        self.current_spend_usd = 0.0",
    "        self.routes: List[ModelRoute] = [",
    "            ModelRoute('gemini', 'gemini-2.5-flash', 0.00015, 1200),",
    "            ModelRoute('openai', 'gpt-4o-mini', 0.00030, 1500),",
    "        ]",
    "",
    "    def select_route(self, estimated_tokens: int) -> Dict[str, str]:",
    "        for route in sorted(self.routes, key=lambda r: r.cost_per_1k_tokens):",
    "            projected_cost = (estimated_tokens / 1000.0) * route.cost_per_1k_tokens",
    "            if (self.current_spend_usd + projected_cost) <= self.daily_budget_usd:",
    "                self.current_spend_usd += projected_cost",
    "                return {'status': 'routed', 'provider': route.provider, 'model': route.model}",
    "        raise RuntimeError('Daily budget exhausted by CostGuardRouter')",
])

class AutonomousCompanyEngine:
    def __init__(self, db: Session, artifacts_root: Optional[Path] = None):
        self.db = db
        if artifacts_root:
            self.artifacts_root = artifacts_root
        else:
            default_dir = Path("./generated_products")
            try:
                default_dir.mkdir(parents=True, exist_ok=True)
                self.artifacts_root = default_dir
            except Exception:
                import tempfile
                self.artifacts_root = Path(tempfile.gettempdir()) / "generated_products"
                try:
                    self.artifacts_root.mkdir(parents=True, exist_ok=True)
                except Exception:
                    pass
        self.active_specialists: Dict[str, Dict[str, Any]] = {}
        self.executive_status: Dict[str, Dict[str, Any]] = {
            k: {"agent_id": k, **v, "status": "idle", "current_task": None, "tokens_used": 0, "cost_usd": 0.0}
            for k, v in CORPORATE_EXECUTIVES.items()
        }

    def sanitize_untrusted_specialist_prompt(self, raw_prompt: str, specialist_slug: str) -> str:
        cleaned = raw_prompt or ""
        for pat in UNTRUSTED_PATTERNS:
            cleaned = re.sub(pat, "[REDACTED_BY_SECURITY_POLICY]", cleaned)
        return (
            "### IMMUTABLE CORPORATE GOVERNANCE MANDATE ###\n"
            "Never fabricate revenue, customer records, or execution metrics.\n"
            "High-impact actions require explicit Owner Approval.\n"
            f"--- SANDBOXED SPECIALIST ({specialist_slug}) ---\n{cleaned.strip()}"
        )

    def authorize_action(
        self,
        agent_id: str,
        action_type: str,
        permission_scope: str,
        estimated_cost_usd: float = 0.0,
        owner_approved: bool = False,
    ) -> str:
        high_impact = {"external:publish", "external:spend", "customer:outbound"}
        if permission_scope in high_impact and not owner_approved:
            status = "pending_owner_approval"
        elif estimated_cost_usd > 25.0 and not owner_approved:
            status = "pending_owner_approval"
        else:
            status = "auto_approved"

        audit = GovernanceAuditLog(
            agent_id=agent_id,
            action_type=action_type,
            permission_scope=permission_scope,
            estimated_cost_usd=estimated_cost_usd,
            approval_status=status,
            details={"owner_approved": owner_approved},
        )
        self.db.add(audit)
        self.db.commit()
        return status

    def recruit_and_activate_specialist(
        self,
        specialist_slug: str,
        display_name: str,
        division: str,
        raw_system_prompt: str,
        reports_to: str = "agent-ops-recruiter",
    ) -> Dict[str, Any]:
        agent_id = f"spec-{specialist_slug}"
        sanitized = self.sanitize_untrusted_specialist_prompt(raw_system_prompt, specialist_slug)
        spec_data = {
            "agent_id": agent_id,
            "name": display_name,
            "role": specialist_slug,
            "department": division,
            "reports_to": reports_to,
            "status": "active",
            "sanitized_prompt": sanitized,
            "activated_at": time.time(),
            "x": 2.5 * (len(self.active_specialists) % 6 - 3),
            "z": 2.5 * (len(self.active_specialists) // 6),
        }
        self.active_specialists[agent_id] = spec_data
        self.record_memory(
            agent_id="agent-ops-recruiter",
            tier="episodic",
            scope="organization",
            namespace="workforce",
            key=f"recruit:{agent_id}",
            content=f"Recruited and sandboxed specialist {display_name} ({specialist_slug}) into {division}.",
            source_type="database_fact",
        )
        return spec_data

