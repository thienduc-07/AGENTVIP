    def record_financial_entry(
        self,
        *,
        entry_type: str,
        amount_usd: float,
        source_verification: str,
        reference_id: str,
        description: str,
        agent_id: str = "agent-fin-controller",
        project_id: Optional[str] = None,
        owner_authorized: bool = True,
    ) -> FinancialLedgerEntry:
        valid_types = {
            "owner_budget_deposit",
            "estimated_revenue",
            "pending_revenue",
            "actual_received_revenue",
            "operating_expense",
            "agent_token_cost",
            "refund",
            "fee",
        }
        if entry_type not in valid_types:
            raise ValueError(f"Invalid financial entry_type: {entry_type}")
        entry = FinancialLedgerEntry(
            entry_type=entry_type,
            amount_usd=round(float(amount_usd), 4),
            project_id=project_id,
            agent_id=agent_id,
            source_verification=source_verification,
            reference_id=reference_id,
            description=description,
            owner_authorized=owner_authorized,
        )
        self.db.add(entry)
        self.db.commit()
        self.db.refresh(entry)
        return entry

    def get_financial_summary(self) -> Dict[str, float]:
        rows = (
            self.db.query(FinancialLedgerEntry.entry_type, func.sum(FinancialLedgerEntry.amount_usd))
            .group_by(FinancialLedgerEntry.entry_type)
            .all()
        )
        totals = {etype: float(val or 0.0) for etype, val in rows}
        deposits = totals.get("owner_budget_deposit", 0.0)
        estimated_rev = totals.get("estimated_revenue", 0.0)
        pending_rev = totals.get("pending_revenue", 0.0)
        actual_rev = totals.get("actual_received_revenue", 0.0)
        opex = totals.get("operating_expense", 0.0) + totals.get("agent_token_cost", 0.0)
        refunds = totals.get("refund", 0.0)
        fees = totals.get("fee", 0.0)
        net_revenue = actual_rev - refunds - fees
        realized_profit = net_revenue - opex
        available_cash = deposits + net_revenue - opex
        return {
            "owner_budget_deposits_usd": round(deposits, 2),
            "estimated_revenue_usd": round(estimated_rev, 2),
            "pending_revenue_usd": round(pending_rev, 2),
            "actual_received_revenue_usd": round(actual_rev, 2),
            "gross_revenue_usd": round(actual_rev, 2),
            "net_revenue_usd": round(net_revenue, 2),
            "operating_expenses_usd": round(opex, 2),
            "realized_profit_usd": round(realized_profit, 2),
            "available_cash_usd": round(available_cash, 2),
        }

